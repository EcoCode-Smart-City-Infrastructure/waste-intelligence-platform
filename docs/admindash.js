/* Admin Dashboard — SAP Smart City Waste Management layout, adapted
   functionally to the Waste Intelligence app (not a picture of it).
   Layout copied from the reference: filter bar (Snapshot / Region /
   District / Building / Bin Type) on top, dark map left, Average Fill +
   Current Waste + Bins Overview right, Bin Incidents table + Waste
   Generated by-the-hour chart below. Every number is computed from the
   same demo fleet / network nodes / history the rest of the app uses,
   and every filter actually re-filters the map, KPIs, incidents and
   chart. Incidents are DERIVED from fleet state (urgent fill, forecast
   to full, feed status) — they are not invented sensor faults — and
   Resolve / Under-review actions persist in this browser
   (wip_admin_incidents). Nothing here claims live sensor data. */
(function(){
'use strict';
const $a = s => document.querySelector(s);
const $$a = s => [...document.querySelectorAll(s)];
const escA = s => String(s??'').replace(/[&<>"]/g,c=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;'}[c]));
let map = null, markerLayer = null, tileSwitched = false, adFitted = false;
function fleetA(){ return (typeof fleet !== 'undefined') ? fleet : (window.wipFleet ? window.wipFleet() : []); }
function histFill(b, snap){
  if(snap>=47) return b.fill;
  if(typeof historyFor !== 'function') return b.fill;
  const pts = historyFor(b); const pt = pts[Math.min(snap, pts.length-1)];
  return pt ? pt.fill : b.fill;
}
function incidentsLoad(){ try{ return JSON.parse(localStorage.getItem('wip_admin_incidents')||'{}'); }catch(e){ return {}; } }
function incidentsSave(o){ try{ localStorage.setItem('wip_admin_incidents', JSON.stringify(o)); }catch(e){} }
function filtered(){
  const region = $a('#adRegion')?.value || 'All';
  const district = $a('#adDistrict')?.value || 'All';
  const building = $a('#adBuilding')?.value || 'All';
  const type = $a('#adBinType')?.value || 'All';
  const snap = +($a('#adSnapshot')?.value || 47);
  return fleetA().map(b=>({...b, _fill: histFill(b, snap)})).filter(b=>
    (region==='All' || b.borough===region) &&
    (district==='All' || b.site===district) &&
    (building==='All' || b.id===building) &&
    (type==='All' || (type==='urgent' && b._fill>=80) || (type==='watch' && b._fill>=60 && b._fill<80) || (type==='ok' && b._fill<60))
  );
}
function fillFilters(){
  const fl = fleetA();
  const region = $a('#adRegion')?.value || 'All';
  const setOpts = (sel, values, cur)=>{
    const all = ['All', ...values];
    sel.innerHTML = all.map(v=>`<option value="${escA(v)}" ${v===cur?'selected':''}>${v==='All'?'All':escA(v)}</option>`).join('');
  };
  const districts = [...new Set(fl.filter(b=>region==='All'||b.borough===region).map(b=>b.site))].sort();
  const districtSel = $a('#adDistrict'); const dCur = districtSel.value;
  setOpts(districtSel, districts, districts.includes(dCur)?dCur:'All');
  const district = districtSel.value;
  const buildings = fl.filter(b=>(region==='All'||b.borough===region) && (district==='All'||b.site===district)).map(b=>b.id);
  const bSel = $a('#adBuilding'); const bCur = bSel.value;
  setOpts(bSel, buildings, buildings.includes(bCur)?bCur:'All');
}
function loadLeafletA(){
  if(window.L) return Promise.resolve(true);
  if(loadLeafletA.p) return loadLeafletA.p;
  loadLeafletA.p = new Promise(res=>{
    const link = document.createElement('link'); link.rel='stylesheet'; link.href='https://unpkg.com/leaflet@1.9.4/dist/leaflet.css'; document.head.appendChild(link);
    const sc = document.createElement('script'); sc.src='https://unpkg.com/leaflet@1.9.4/dist/leaflet.js'; sc.onload=()=>res(!!window.L); sc.onerror=()=>res(false); document.body.appendChild(sc);
  });
  return loadLeafletA.p;
}
async function renderMap(bins){
  const el = $a('#adMap'); if(!el) return;
  const ok = await loadLeafletA();
  if(!ok || !window.L){ el.innerHTML = '<p class="muted small" style="padding:1rem">Map library failed to load — check connection and reopen this view. The KPIs, incidents and chart below still work.</p>'; return; }
  if(!map){
    map = window.L.map(el, {preferCanvas:true}).setView([40.7128,-74.006], 11);
    const base = window.L.tileLayer('https://tile.openstreetmap.org/{z}/{x}/{y}.png', {maxZoom:19, attribution:'&copy; OpenStreetMap contributors'});
    let errs = 0;
    base.on('tileerror', ()=>{ errs++; if(errs>=5 && !tileSwitched){ tileSwitched = true; map.removeLayer(base); window.L.tileLayer('https://tile.openstreetmap.org/{z}/{x}/{y}.png', {maxZoom:19, attribution:'&copy; OpenStreetMap contributors'}).addTo(map); } });
    base.addTo(map);
    markerLayer = window.L.layerGroup().addTo(map);
    setTimeout(()=>{ try{ map.invalidateSize(); }catch(e){} }, 150);
  }
  if(!adFitted && bins.length){
    adFitted = true;
    try{ map.fitBounds(window.L.latLngBounds(bins.map(b=>[b.lat,b.lon])), {padding:[24,24]}); }catch(e){}
  }
  markerLayer.clearLayers();
  bins.forEach(b=>{
    const col = b._fill>=80 ? '#f87171' : b._fill>=60 ? '#f59e0b' : '#22c55e';
    window.L.circleMarker([b.lat,b.lon], {radius:6+b._fill/14, color:'#0f172a', weight:1.5, fillColor:col, fillOpacity:0.95})
      .bindPopup(`<strong>${escA(b.id)}</strong><br>${escA(b.site)}, ${escA(b.borough)}<br>Fill ${b._fill}%<br><a href="#forecast?bin=${encodeURIComponent(b.id)}">Open forecast →</a>`)
      .addTo(markerLayer);
  });
}
function render(){
  fillFilters();
  const bins = filtered();
  const snap = +($a('#adSnapshot')?.value || 47);
  const avg = bins.length ? bins.reduce((s,b)=>s+b._fill,0)/bins.length : 0;
  $a('#adAvgFill').textContent = Math.round(avg) + '%';
  $a('#adAvgBar').style.width = Math.round(avg) + '%';
  $a('#adAvgSub').textContent = `Actual volume / total capacity · ${bins.length} bin${bins.length===1?'':'s'} in filter · snapshot ${snap>=47?'now':'hour '+snap+' of 48'}`;
  const tpf = (()=>{ try{ return +JSON.parse(localStorage.getItem('wip_admin_settings')||'{}').tonnesPerFull || 0.5; }catch(e){ return 0.5; } })();
  const waste = bins.reduce((s,b)=>s + tpf*b._fill/100, 0);
  $a('#adWaste').textContent = waste.toFixed(1);
  $a('#adWasteSub').textContent = `Modelled from fill × ${tpf} t per full node (Admin default) — not a weighed total.`;
  const outOfOrder = bins.filter(b=>b._fill>=95).length;
  let nodes = 0; try{ nodes = JSON.parse(localStorage.getItem('wip_network_nodes')||'[]').length; }catch(e){}
  $a('#adTotalBins').textContent = bins.length;
  $a('#adOutOrder').textContent = outOfOrder;
  $a('#adNodes').textContent = nodes;
  // Hourly chart: actual = mean fill per hour (demo history), forecast = trend extension
  const hours = [];
  for(let h=0; h<48; h++){
    const vals = fleetA().map(b=>{ const pts = (typeof historyFor==='function') ? historyFor(b) : []; const pt = pts[Math.min(h, pts.length-1)]; return pt?pt.fill:b.fill; });
    hours.push(vals.length ? vals.reduce((s,v)=>s+v,0)/vals.length : 0);
  }
  const last = hours[hours.length-1] || 0;
  const slope = hours.length>1 ? (last - hours[0])/47 : 0;
  const fc = hours.map((v,i)=> Math.min(100, Math.max(0, last + slope*(i-47))));
  const X = i=>20+i/47*460, Y = v=>140-v/100*120;
  const line = arr => arr.map((v,i)=>`${i?'L':'M'}${X(i).toFixed(1)},${Y(v).toFixed(1)}`).join(' ');
  $a('#adHourSvg').innerHTML = `<path d="${line(hours)}" fill="none" stroke="#22c55e" stroke-width="2.5"/><path d="${line(fc)}" fill="none" stroke="#94a3b8" stroke-width="2" stroke-dasharray="6 5"/>`;
  $a('#adHourNote').textContent = 'Green = actual mean fill by hour (demo history, 48 h). Grey dashed = trend extension from the last hour — a guide, not a forecast guarantee.';
  // Incidents, derived from filtered fleet state
  const saved = incidentsLoad();
  const inc = [];
  bins.filter(b=>b._fill>=80).forEach(b=>inc.push({key:'fill-'+b.id, ticket:'108'+(inc.length+1), title:`Bin ${b.id} at ${b._fill}% fill`, type:'Fill', reported:'System', status:'Under review'}));
  bins.filter(b=>b._fill>=95).forEach(b=>inc.push({key:'ooo-'+b.id, ticket:'133'+(inc.length+1), title:`Bin ${b.id} flagged out of order (≥95% fill)`, type:'Out of order', reported:'System', status:'Under review'}));
  const top = [...bins].sort((a,b)=>b._fill-a._fill)[0];
  if(top && typeof analyse==='function' && typeof historyFor==='function'){
    const a = analyse(historyFor(top));
    if(a.toFull!==Infinity) inc.push({key:'fc-'+top.id, ticket:'127'+(inc.length+1), title:`Bin ${top.id} fills in ~${Math.round(a.toFull)} hours at current trend`, type:'Forecast', reported:'System', status:'Under review'});
  }
  inc.push({key:'feed', ticket:'1547', title:'DSNY tonnage feed status (see Dashboard badge)', type:'Feed', reported:'System', status:'Under review'});
  const rows = inc.map((r,i)=>{
    const st = saved[r.key] || r.status;
    return `<tr><td>${r.ticket}</td><td>${escA(r.title)}</td><td>${r.type}</td><td>${r.reported}</td><td>${st}</td><td><button class="btn" data-res="${escA(r.key)}">Resolve</button> <button class="btn" data-und="${escA(r.key)}">Under</button></td></tr>`;
  }).join('') || '<tr><td colspan="6">No incidents in this filter.</td></tr>';
  $a('#adIncidents').innerHTML = rows;
  $a('#adIncCount').textContent = `Total ${inc.length} · Resolve ${inc.filter(r=>(saved[r.key]||r.status)==='Resolved').length} · Under ${inc.filter(r=>(saved[r.key]||r.status)==='Under review').length}`;
  $$a('#adIncidents [data-res]').forEach(b=>b.addEventListener('click',()=>{ const s = incidentsLoad(); s[b.dataset.res]='Resolved'; incidentsSave(s); render(); }));
  $$a('#adIncidents [data-und]').forEach(b=>b.addEventListener('click',()=>{ const s = incidentsLoad(); s[b.dataset.und]='Under review'; incidentsSave(s); render(); }));
  // Lazy map: only load Leaflet when the Admin Dashboard view is actually shown.
  if(!$a('#view-admindash')?.classList.contains('hidden')) renderMap(bins);
}
function init(){
  if(!$a('#view-admindash')) return;
  const region = $a('#adRegion');
  if(region && !region.dataset.filled){
    region.dataset.filled = '1';
    const boroughs = [...new Set(fleetA().map(b=>b.borough))].sort();
    region.innerHTML = '<option value="All">All regions</option>' + boroughs.map(b=>`<option value="${escA(b)}">${escA(b)}</option>`).join('');
  }
  ['adSnapshot','adRegion','adDistrict','adBuilding','adBinType'].forEach(id=> $a('#'+id)?.addEventListener('change', render));
  $a('#adResetInc')?.addEventListener('click', ()=>{ try{ localStorage.removeItem('wip_admin_incidents'); }catch(e){} render(); });
  window.addEventListener('hashchange', ()=>{ if((location.hash||'').split('?')[0]==='#admindash'){ render(); setTimeout(()=>{ try{ if(map) map.invalidateSize(); }catch(e){} }, 100); } });
  render();
}
if(document.readyState==='loading') document.addEventListener('DOMContentLoaded', init); else init();
})();
