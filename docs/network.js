function hav(lat1,lon1,lat2,lon2){ const R=6371, dLa=(lat2-lat1)*Math.PI/180, dLo=(lon2-lon1)*Math.PI/180, a=Math.sin(dLa/2)**2+Math.cos(lat1*Math.PI/180)*Math.cos(lat2*Math.PI/180)*Math.sin(dLo/2)**2; return 2*R*Math.asin(Math.sqrt(a)); }
