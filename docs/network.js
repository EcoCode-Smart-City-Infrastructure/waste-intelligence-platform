/* Collection Network — generative, modelled, NOT DSNY truck GPS.
   Public spine (live Socrata, no key):
   - DSNY Frequencies rv63-53db: district/section -> freq_refuse, freq_recycling,
     freq_organics, freq_bulk. Section-level schedule, NOT a route order.
   - DSNY Districts With Disposal Vendor Assignments fpv2-r9br: district ->
     org_curb_pri, mgp_curb_pri, pap_curb_pri, ref_curb_pri destinations.
   - DSNY Monthly Tonnage ebb7-mvp5 is the district-month tonnage spine
     (used in Live view); this network does not invent district tonnage.
   Generative layer (this file, browser-local):
   - Nodes: demo fleet bins + user-added collection nodes, hubs, distribution
     points and gardens (saved to localStorage wip_network_nodes).
   - Sequence: greedy nearest-neighbour from a hub, hub-and-spoke return.
     That order is GENERATED, never presented as DSNY's actual route order.
   - Events: logged by the user (or generated by running a sequence).
     Each event carries tonnes, stream, sequence and a conversion chain
     from kg.json (organics only for full conversion; other streams show
     collection + vendor destination, no invented conversion).
   Tonnes per full node is a labelled demo assumption (default 0.5 t),
   editable in the form — it is not a DSNY measurement. */
(function(){
'use strict';
const $n = s => document.querySelector(s);
const $$n = s => [...document.querySelectorAll(s)];
const escN = s => String(s??'').replace(/[&<>"]/g,c=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;'}[c]));
const fmtN = n => (n==null||isNaN(n)?'—':Number(n).toLocaleString(undefined,{maximumFractionDigits:2}));
const BORO = {Manhattan:[40.7831,-73.9712],Brooklyn:[40.6782,-73.9442],Queens:[40.7282,-73.7949],Bronx:[40.8448,-73.8648],'Staten Island':[40.5795,-74.1502]};
const STREAM_COLOUR = {organics:'#22c55e',refuse:'#64748b',recycling:'#2dd4bf',paper:'#2dd4bf',mgp:'#f59e0b',yard:'#84cc16'};
let kg = null, hubs = [], spine = null, sequence = [], currentHub = null;
function loadNodes(){ try{ return JSON.parse(localStorage.getItem('wip_network_nodes')||'[]'); }catch(e){ return []; } }
function saveNodes(a){ try{ localStorage.setItem('wip_network_nodes', JSON.stringify(a)); }catch(e){} }
function loadEvents(){ try{ return JSON.parse(localStorage.getItem('wip_network_events')||'[]'); }catch(e){ return []; } }
function saveEvents(a){ try{ localStorage.setItem('wip_network_events', JSON.stringify(a)); }catch(e){} }
function hav(lat1,lon1,lat2,lon2){ const R=6371, dLa=(lat2-lat1)*Math.PI/180, dLo=(lon2-lon1)*Math.PI/180, a=Math.sin(dLa/2)**2+Math.cos(lat1*Math.PI/180)*Math.cos(lat2*Math.PI/180)*Math.sin(dLo/2)**2; return 2*R*Math.asin(Math.sqrt(a)); }
function fleetNodes(){
  let f = [];
  try{ f = (typeof window.wipFleet==='function'?window.wipFleet():[])||[]; }catch(e){}
  return f.map(b=>({id:b.id, site:b.site, kind:'collection bin', stream:'organics', host:'DSNY', borough:b.borough, lat:b.lat, lon:b.lon, fill:b.fill||0, source:'demo fleet (Bins & Routes)' }));
}
function allNodes(){ return [...hubs, ...fleetNodes(), ...loadNodes()]; }
function hubForStream(stream){
  // Prefer a KG facility that supports the process for this stream and
  // accepts its waste; fall back to the first hub. Vendor destination
  // text from the public spine is shown alongside, not forced onto a pin.
  const proc = stream==='organics' ? 'AerobicComposting' : null;
  if(proc && kg){
    const sup = kg.edges.filter(e=>e.type==='FACILITYSUPPORTSPROCESS'&&e.to===proc).map(e=>e.from);
    const h = hubs.find(x=>sup.includes(x.id));
    if(h) return h;
  }
  return hubs[0]||null;
}
function destText(stream){
  if(!spine || !spine.vendor) return '— (load a district spine above)';
  const v = spine.vendor;
  if(stream==='organics') return v.org_curb_pri||'—';
  if(stream==='recycling'||stream==='mgp') return v.mgp_curb_pri||'—';
  if(stream==='paper') return v.pap_curb_pri||'—';
  if(stream==='refuse') return v.ref_curb_pri||'—';
  return '—';
}
function renderHubs(){
  const el = $n('#netHubs'); if(!el) return;
  el.innerHTML = hubs.map(h=>`<li><strong>${escN(h.site)}</strong> — ${escN(h.kind)} · ${escN(h.borough||'')} ${h.approx?'· <span class="muted">position approximate (borough centre, no lat/lon in kg.json)</span>':''} · ${escN(h.source||'kg.json')}</li>`).join('') || '<li>—</li>';
}
function renderNodes(){
  const el = $n('#netNodeList'); if(!el) return;
  const nodes = allNodes();
  el.innerHTML = nodes.map(x=>`<li><strong>${escN(x.id)}</strong> — ${escN(x.site)} · ${escN(x.kind)} · ${escN(x.stream)} · host ${escN(x.host)} · ${escN(x.borough)} ${x.fill!=null?`· fill ${x.fill}%`:''}</li>`).join('') || '<li>—</li>';
  const sel = $n('#netHubSelect'); if(sel){ const cur = sel.value; sel.innerHTML = hubs.map(h=>`<option value="${h.id}">${escN(h.site)}</option>`).join(''); if(cur) sel.value = cur; }
}
function xy(lat,lon){ const x = 20 + (lon - (-74.25)) / (-73.70 - (-74.25)) * 860; const y = 500 - (lat - 40.49) / (40.92 - 40.49) * 480; return [x,y]; }
function drawMap(){
  const svg = $n('#netMap'); if(!svg) return;
  const nodes = allNodes();
  let html = '';
  if(sequence.length && currentHub){
    const pts = [currentHub, ...sequence, currentHub];
    html += `<path d="${pts.map((p,i)=>`${i?'L':'M'}${xy(p.lat,p.lon).join(',')}`).join(' ')}" fill="none" stroke="#1d7a4f" stroke-width="2.5" stroke-dasharray="6 4"/>`;
  }
  html += nodes.map(x=>{
    const [cx,cy] = xy(x.lat,x.lon);
    const isHub = x.kind==='hub' || x.kind==='facility';
    return isHub
      ? `<g><rect x="${cx-7}" y="${cy-7}" width="14" height="14" fill="#2563eb" stroke="#fff" stroke-width="1.5"/><text x="${cx}" y="${cy+24}" text-anchor="middle" font-size="10">${escN((x.site||'').slice(0,18))}</text></g>`
      : `<g><circle cx="${cx}" cy="${cy}" r="6" fill="${STREAM_COLOUR[x.stream]||'#22c55e'}" stroke="#fff" stroke-width="1.5"/><text x="${cx}" y="${cy+20}" text-anchor="middle" font-size="10">${escN((x.site||x.id||'').slice(0,16))}</text></g>`;
  }).join('');
  svg.innerHTML = html;
}
function conversionFor(stream, process, tonnes){
  if(stream!=='organics' || !kg) return {diverted:0, co2:0, ch4:0, resource:0, resourceName:'—', note:'Full conversion chain is modelled for organics only. Other streams show collection + vendor destination; no conversion is invented for them.'};
  const edge = kg.edges.find(e=>e.from==='ResidentialOrganicsCitywide'&&e.to===process&&e.type==='WASTECANBEPROCESSEDBY')
    || kg.edges.find(e=>e.from==='FoodScraps'&&e.to===process&&e.type==='WASTECANBEPROCESSEDBY');
  const div = edge?.props?.typical_diversion_rate ?? 0.85;
  const co2f = edge?.props?.co2e_saved_mt_per_metric_tonne_warm_v15 ?? (process==='AnaerobicDigestion'?0.62:0.68);
  const ch4f = edge?.props?.methane_avoided_kg_per_tonne ?? 23.2;
  const pr = kg.edges.find(e=>e.from===process&&e.to==='CompostAmendment'&&e.type==='PROCESSPRODUCESRESOURCE');
  const yld = pr?.props?.yield_tonnes_per_tonne_waste ?? 0.4;
  const diverted = tonnes * div;
  return {diverted, co2: diverted * co2f, ch4: diverted * ch4f, resource: diverted * yld, resourceName:'Compost Amendment',
    note:`WARM v15 via kg.json edge (${process}): diversion ${Math.round(div*100)}%, ${co2f} MTCO₂e/t diverted, ${ch4f} kg CH₄/t diverted, compost yield ${yld} t/t diverted. Methane is inside the WARM CO₂e factor — never add them.`};
}
function renderEvents(){
  const ev = loadEvents();
  const el = $n('#netEvents'); if(!el) return;
  el.innerHTML = ev.slice().reverse().slice(0,50).map(e=>`<li><strong>${escN(e.nodeSite)}</strong> · ${escN(e.stream)} · ${fmtN(e.tonnes)} t · ${escN(e.process||'collection only')} → ${escN(e.destination||'—')} · ${escN(new Date(e.at).toLocaleString())} · seq ${escN(e.seq||'—')}</li>`).join('') || '<li>No collection events logged yet.</li>';
  const t = ev.reduce((a,e)=>a+ (e.tonnes||0), 0), d = ev.reduce((a,e)=>a+(e.diverted||0),0),
        c = ev.reduce((a,e)=>a+(e.co2||0),0), m = ev.reduce((a,e)=>a+(e.ch4||0),0), r = ev.reduce((a,e)=>a+(e.resource||0),0);
  const k = $n('#netKpis'); if(k) k.innerHTML = `<div><b>${ev.length}</b><span>Collection events</span></div><div><b>${fmtN(t)} t</b><span>Collected (logged)</span></div><div><b>${fmtN(d)} t</b><span>Diverted (modelled)</span></div><div><b>${fmtN(c)} MTCO₂e</b><span>Avoided vs landfill (WARM v15)</span></div><div><b>${fmtN(m)} kg</b><span>Methane avoided (CH₄ only)</span></div><div><b>${fmtN(r)} t</b><span>Compost / resource out</span></div>`;
}
function buildSequence(){
  const stream = $n('#netStream').value;
  const borough = $n('#netBorough').value;
  const hubId = $n('#netHubSelect').value;
  currentHub = hubs.find(h=>h.id===hubId) || hubForStream(stream);
  const pool = allNodes().filter(x=>x.kind!=='hub'&&x.kind!=='facility'&&(x.stream===stream||x.kind==='collection bin')&&(!borough||x.borough===borough));
  const rest = [...pool]; const order = []; let cur = currentHub;
  while(rest.length){
    let bi = 0, bd = Infinity;
    rest.forEach((x,i)=>{ const d = cur?hav(cur.lat,cur.lon,x.lat,x.lon):0; if(d<bd){bd=d;bi=i;} });
    order.push(rest.splice(bi,1)[0]); cur = order[order.length-1];
  }
  sequence = order;
  let dist = 0; const pts = currentHub?[currentHub,...order,currentHub]:order;
  for(let i=1;i<pts.length;i++) dist += hav(pts[i-1].lat,pts[i-1].lon,pts[i].lat,pts[i].lon);
  $n('#netSeqSummary').textContent = order.length
    ? `${order.length} stops · hub ${currentHub?currentHub.site:'—'} → return · ${dist.toFixed(1)} km straight-line segments · about ${Math.round(dist/22*60+order.length*6)} min at city pace + 6 min per stop · scheduled day (public spine): ${spine? (spine.freq?.['freq_'+stream]||spine.freq?.freq_organics||'load a district above') : 'load a district above'} · vendor destination: ${destText(stream)}`
    : 'No stops match that stream/borough — add a collection node below, or pick another borough.';
  $n('#netSeqList').innerHTML = order.map((x,i)=>`<li><strong>${i+1}. ${escN(x.site)}</strong> — ${escN(x.id)} · ${escN(x.stream)} · host ${escN(x.host)} · fill ${x.fill!=null?x.fill+'%':'—'}</li>`).join('');
  drawMap();
}
function logEvent(node, seqId, at){
  const stream = $n('#netStream').value, process = $n('#netProcess').value;
  const perFull = Math.max(0, +$n('#netTonnesPerFull').value || 0.5);
  const tonnes = (node.fill!=null? node.fill/100 : 0.5) * perFull;
  const conv = conversionFor(stream, process, tonnes);
  const ev = loadEvents();
  ev.push({at: at||new Date().toISOString(), nodeId: node.id, nodeSite: node.site, stream, process: stream==='organics'?process:'collection only',
    tonnes, diverted: conv.diverted, co2: conv.co2, ch4: conv.ch4, resource: conv.resource, resourceName: conv.resourceName,
    destination: currentHub? currentHub.site : destText(stream), seq: seqId, note: conv.note});
  saveEvents(ev);
  // A collected bin empties in the demo fleet, so the next sequence sees it empty.
  try{ const f = window.wipFleet && window.wipFleet(); const b = f && f.find(x=>x.id===node.id); if(b){ b.fill = 0; if(window.saveFleet) window.saveFleet(); } }catch(e){}
  renderEvents(); renderNodes(); drawMap();
}
async function loadSpine(){
  const dist = ($n('#netDistrict').value||'').trim().toUpperCase();
  const out = $n('#netSpine'); if(!dist){ out.textContent = 'Enter a district code, e.g. BKN05, MAN01, QN07, BX03, SI01.'; return; }
  out.textContent = 'Loading public spine…';
  try{
    const fq = await (await fetch(`https://data.cityofnewyork.us/resource/rv63-53db.json?$select=district,section,freq_refuse,freq_recycling,freq_organics,freq_bulk&district=${encodeURIComponent(dist)}&$limit=100`)).json();
    const va = await (await fetch(`https://data.cityofnewyork.us/resource/fpv2-r9br.json?$select=district,org_curb_pri,mgp_curb_pri,pap_curb_pri,ref_curb_pri&district=${encodeURIComponent(dist)}&$limit=10`)).json();
    if(!fq.length){ out.textContent = `No Frequencies rows for ${dist} — check the code (district codes look like BKN05, MAN01, QN07, BX03, SI01).`; spine = null; return; }
    spine = {district: dist, freq: fq[0], sections: fq, vendor: va[0]||null};
    out.innerHTML = `<strong>${dist}</strong> — ${fq.length} section(s). First section ${escN(fq[0].section)}: refuse ${escN(fq[0].freq_refuse)}, recycling ${escN(fq[0].freq_recycling)}, organics ${escN(fq[0].freq_organics)}, bulk ${escN(fq[0].freq_bulk)}. ${va[0]?`Vendor destinations — organics: ${escN(va[0].org_curb_pri||'—')}; MGP: ${escN(va[0].mgp_curb_pri||'—')}; paper: ${escN(va[0].pap_curb_pri||'—')}; refuse: ${escN(va[0].ref_curb_pri||'—')}.`:''} <span class="muted small">Sources: DSNY Frequencies rv63-53db; DSNY Vendor Assignments fpv2-r9br. Section schedules only — no turn-by-turn route order is published.</span>`;
    $n('#netSpineTable').innerHTML = fq.map(r=>`<tr><td>${escN(r.section)}</td><td>${escN(r.freq_refuse)}</td><td>${escN(r.freq_recycling)}</td><td>${escN(r.freq_organics)}</td><td>${escN(r.freq_bulk)}</td></tr>`).join('');
  }catch(e){ out.textContent = 'Could not reach NYC Open Data — check connection and retry. Nothing here is cached as a substitute.'; }
}
async function init(){
  if(!$n('#view-network')) return;
  try{ kg = await (await fetch('kg.json')).json(); }catch(e){ kg = null; }
  if(kg){
    hubs = kg.nodes.filter(n=>n.type==='Facility').map(n=>{
      const loc = n.detail?.location||{};
      const has = loc.latitude!=null && loc.longitude!=null;
      return {id:n.id, site:n.name, kind:'hub', stream:'organics', host:'DSNY / operator (see kg detail)', borough:loc.borough||'', lat:has?loc.latitude:(BORO[loc.borough]||BORO.Brooklyn)[0], lon:has?loc.longitude:(BORO[loc.borough]||BORO.Brooklyn)[1], approx:!has, source:'kg.json facility'};
    });
  }
  renderHubs(); renderNodes(); renderEvents(); drawMap();
  $n('#netSpineBtn')?.addEventListener('click', loadSpine);
  $n('#netBuildBtn')?.addEventListener('click', buildSequence);
  $n('#netRunBtn')?.addEventListener('click', ()=>{
    if(!sequence.length){ $n('#netSeqSummary').textContent = 'Build a sequence first.'; return; }
    const seqId = 'SEQ-' + new Date().toISOString().slice(0,10) + '-' + String(loadEvents().length+1);
    const base = Date.now();
    sequence.forEach((x,i)=> logEvent(x, seqId, new Date(base + i*6*60000).toISOString()));
    $n('#netSeqSummary').textContent += ` · Logged ${sequence.length} collection events as ${seqId} (6 min apart, modelled timing).`;
  });
  $n('#netClearEventsBtn')?.addEventListener('click', ()=>{ saveEvents([]); renderEvents(); });
  $n('#netExportBtn')?.addEventListener('click', ()=>{
    const blob = new Blob([JSON.stringify({nodes: loadNodes(), events: loadEvents(), spine, exported_at: new Date().toISOString()}, null, 2)], {type:'application/json'});
    const a = document.createElement('a'); a.href = URL.createObjectURL(blob); a.download = 'collection-network.json'; a.click();
  });
  $n('#netNodeForm')?.addEventListener('submit', e=>{
    e.preventDefault();
    const borough = $n('#netNodeBorough').value;
    const node = {id: $n('#netNodeId').value.trim(), site: $n('#netNodeSite').value.trim(),
      kind: $n('#netNodeKind').value, stream: $n('#netNodeStream').value, host: $n('#netNodeHost').value,
      borough, lat: +$n('#netNodeLat').value || BORO[borough][0], lon: +$n('#netNodeLon').value || BORO[borough][1],
      fill: $n('#netNodeKind').value==='collection bin' ? (+$n('#netNodeFill').value||0) : undefined,
      source: 'user-added network node (this browser)'};
    if(!node.id || !node.site) return;
    const nodes = loadNodes(); nodes.unshift(node); saveNodes(nodes);
    renderNodes(); drawMap(); e.target.reset();
  });
  window.addEventListener('hashchange', ()=>{ if((location.hash||'').startsWith('#network')){ renderNodes(); renderEvents(); drawMap(); } });
}
if(document.readyState==='loading') document.addEventListener('DOMContentLoaded', init); else init();
})();
